// Writes docs/COMPONENTS.md: one line per Storybook entry (where it lives, what it is for, its stories), read from the
// stories and the component's doc comment, so the index follows Storybook. Beside it, public/llms.txt (llmstxt.org):
// the tiers, the entry points and the docs' links, for an agent that starts from the live site (the site build copies
// it to its root). `--check` fails when either file is stale.
import {readFileSync, readdirSync, writeFileSync, existsSync} from 'node:fs';

const OUT = 'docs/COMPONENTS.md';
const LLMS = 'public/llms.txt';
const SITE = 'https://andratwiro.github.io/govocal-ds';
const RAW = 'https://raw.githubusercontent.com/andratwiro/govocal-ds/main';
const files = readdirSync('src', {recursive: true}).filter(f => f.endsWith('.stories.tsx')).sort();

// The first sentence of the JSDoc right above `export function|const <Name>`, prototype asides dropped.
function purpose(source, name) {
  const m = source.match(new RegExp(`/\\*\\*((?:(?!\\*/)[\\s\\S])*)\\*/\\s*export (?:function|const) ${name}\\b`)) ??
    source.match(new RegExp(`((?:^//.*\\n)+)export (?:function|const) ${name}\\b`, 'm'));
  if (!m) return '';
  const text = m[1].replace(/^\s*(?:\*|\/\/)\s?/gm, ' ').replace(/\s+/g, ' ').replace(/\s*\([^)]*prototype[^)]*\)/gi, '').trim();
  const first = text.match(/^.*?[.;](?=\s+[A-Z`]|$)/)?.[0] ?? text;
  return first.length > 160 ? first.slice(0, 157).trimEnd() + '…' : first;
}

const groups = new Map();
const names = new Map();  // group → the entries' exports (or names), for llms.txt
const notInFigma = [];
for (const f of files) {
  const s = readFileSync(`src/${f}`, 'utf8');
  const meta = s.match(/const meta[^=]*=\s*\{([\s\S]*?)\n\};/)?.[1] ?? '';
  const title = meta.match(/title:\s*'([^']+)'/)?.[1] ?? (/^components\/\w+\.stories/.test(f) ? `Base/${f.match(/(\w+)\.stories/)[1]}` : null);
  if (!title || !/^(Components|Patterns|Base|Foundations)\//.test(title)) continue;
  const component = meta.match(/component:\s*([A-Z]\w*)/)?.[1];
  const from = component && s.match(new RegExp(`import\\s*\\{[^}]*\\b${component}\\b[^}]*\\}\\s*from\\s*'(\\.[^']+)'`))?.[1];
  const srcFile = from && [`.tsx`, `/index.tsx`].map(ext => `src/${f.replace(/[^/]+$/, '')}${from}${ext}`)
    .map(p => p.replace(/\/\.\//g, '/')).find(p => existsSync(p));
  // A recipe (a story file with no component of its own) says what it is for in the doc comment above its meta.
  const what = (srcFile ? purpose(readFileSync(srcFile, 'utf8'), component) : '') ||
    purpose(s.replace(/\*\/\s*const meta\b/, '*/\nexport const meta'), 'meta');
  const stories = [...s.matchAll(/^export const ([A-Z]\w*)\s*:\s*Story\b/gm)].map(m => m[1].replace(/(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])|(?<=[a-z])(?=[0-9])/g, ' '));
  const parts = title.split('/');
  const group = parts.slice(0, -1).join(' / ');
  const tag = /not-in-figma/.test(s) ? ' (not in Figma)' : '';
  const line = `- **${parts.at(-1)}**${component ? ` \`${component}\`` : ''}${tag}${what ? `: ${what}` : ''}` +
    (stories.length ? ` Stories: ${stories.join(', ')}.` : '');
  if (tag) notInFigma.push(parts.at(-1));
  if (!groups.has(group)) { groups.set(group, []); names.set(group, []); }
  groups.get(group).push(line);
  const name = parts.at(-1);
  // A recipe is markup to copy, not an export to import: its name alone.
  names.get(group).push(!component || parts.includes('Recipes') ? name : name.replace(/\s+/g, '').toLowerCase() === component.toLowerCase()
    ? `\`${component}\`` : `${name} (\`${component}\`)`);
}

const body = [`# Components index`, ``,
  `Generated by \`npm run components:index\` from the stories; never edit by hand. One line per Storybook entry:`,
  `name, export, what it is for, its stories (each story is a configuration to copy). Search it before drawing UI;`,
  `then open that entry's stories file for the usage. Import paths and props: docs/API.md.`, ``,
  ...[...groups].flatMap(([g, lines]) => [`## ${g}`, ...lines, ``]),
  `## Not in Figma yet`, `Tagged \`not-in-figma\` in their stories (${notInFigma.length}): ${notInFigma.join(', ')}.`, ``].join('\n');

const TIERS = [
  ['Components', 'Generic parts any admin could ship, from `govocal-ds`. Reach for one first.'],
  ['Patterns', 'Go Vocal assemblies from `govocal-ds`, grouped by the screen they belong to; their props speak phases, ' +
    'methods, projects. Use one when your screen is that place.'],
  ['Base', "React Aria's starter parts painted with the tokens, from `govocal-ds/base`. Only when no Component does " +
    'the job, never in place of one.']
];
const tierLines = tier => [...names].filter(([g]) => g === tier || g.startsWith(`${tier} / `))
  .map(([g, list]) => `- ${g === tier ? '' : `${g.slice(tier.length + 3)}: `}${list.join(', ')}`);
const llms = [`# Go Vocal design system`, ``,
  `> Go Vocal's admin components: React Aria Components 1.22 painted only with \`--gv-*\` design tokens (from Figma),`,
  `> shown in Storybook, with a demo back office built from them alone. Import from three entry points; reach for a`,
  `> Component first; paint only with the tokens.`, ``,
  `Generated by \`npm run components:index\` from the stories, beside docs/COMPONENTS.md; never edit by hand.`, ``,
  `- Entry points: \`govocal-ds\` (Components, Patterns, \`AppProvider\`, React Aria's value types),`,
  `  \`govocal-ds/base\` (Base parts), \`govocal-ds/tokens.css\` (the tokens, imported once at the app's root). Never`,
  `  import a file path.`,
  `- Wrap the app once in \`AppProvider\` (locale, router, the toast region). Words a part says come in as props.`,
  `- Paint only with \`var(--gv-*)\`, semantic tokens first, from tokens.json (below); never guess a token name.`,
  `- Three tiers, in the order to reach for them: ${TIERS.map(([t]) => t).join(', ')} (one section each, below).`, ``,
  `## Docs`, ``,
  `- [AGENTS.md](${RAW}/AGENTS.md): the agent's map: tiers, entry points, finding a part, tokens, commands, MCP servers, hard rules`,
  `- [API.md](${RAW}/docs/API.md): imports, props, \`className\` and \`style\`, the naming convention`,
  `- [COMPONENTS.md](${RAW}/docs/COMPONENTS.md): one line per Storybook entry: its export, what it is for, its stories`,
  `- [CONSUMING.md](${RAW}/docs/CONSUMING.md): using it from another app: the build, CSS scoping, providers, forms`,
  `- [tokens.json](${SITE}/tokens.json): every \`--gv-*\` token as DTCG JSON, with its purpose`,
  `- [Components manifest](${SITE}/storybook/manifests/components.json): every entry's props and its stories' code`, ``,
  ...TIERS.flatMap(([t, what]) => [`## ${t}`, ``, what, ``, ...tierLines(t), ``]),
  `## Optional`, ``,
  `- [Storybook](${SITE}/storybook/): every part, every state, left to right and right to left`,
  `- [The back office](${SITE}/backoffice/): a demo admin built only from the entry points`,
  `- [HOW-TO.md](${RAW}/docs/HOW-TO.md): the designer's recipes: change a token, a look, add a story`,
  `- [NAMING.md](${RAW}/docs/NAMING.md): names, the Storybook tree, tags, what becomes a component`,
  `- [DESIGN.md](${RAW}/docs/DESIGN.md): why it is built this way`, ``].join('\n');

const outputs = [[OUT, body], [LLMS, llms]];
if (process.argv.includes('--check')) {
  for (const [file, text] of outputs) {
    const now = existsSync(file) ? readFileSync(file, 'utf8') : '';
    if (now !== text) { console.error(`${file} is stale: run npm run components:index`); process.exit(1); }
  }
} else {
  for (const [file, text] of outputs) writeFileSync(file, text);
  console.log(`${OUT}: ${[...groups.values()].flat().length} entries, ~${Math.round(body.length / 4)} tokens; ` +
    `${LLMS}: ~${Math.round(llms.length / 4)} tokens`);
}
