// Writes docs/COMPONENTS.md: one line per Storybook entry (where it lives, what it is for, its stories), read from the
// stories and the component's doc comment, so the index follows Storybook. `--check` fails when the file is stale.
import {readFileSync, readdirSync, writeFileSync, existsSync} from 'node:fs';

const OUT = 'docs/COMPONENTS.md';
const files = readdirSync('src', {recursive: true}).filter(f => f.endsWith('.stories.tsx')).sort();

// The first sentence of the JSDoc right above `export function|const <Name>`, prototype asides dropped.
function purpose(source, name) {
  const m = source.match(new RegExp(`/\\*\\*((?:(?!\\*/)[\\s\\S])*)\\*/\\s*export (?:function|const) ${name}\\b`)) ??
    source.match(new RegExp(`((?:^//.*\\n)+)export (?:function|const) ${name}\\b`, 'm'));
  if (!m) return '';
  const text = m[1].replace(/^\s*(?:\*|\/\/)\s?/gm, ' ').replace(/\s+/g, ' ').replace(/\s*\([^)]*prototype[^)]*\)/gi, '').trim();
  const first = text.match(/^.*?[.;](?=\s+[A-Z`]|$)/)?.[0] ?? text;
  return first.length > 160 ? first.slice(0, 157).trimEnd() + '…' : first;
}

const groups = new Map();
const notInFigma = [];
for (const f of files) {
  const s = readFileSync(`src/${f}`, 'utf8');
  const meta = s.match(/const meta[^=]*=\s*\{([\s\S]*?)\n\};/)?.[1] ?? '';
  const title = meta.match(/title:\s*'([^']+)'/)?.[1] ?? (/^components\/\w+\.stories/.test(f) ? `Base/${f.match(/(\w+)\.stories/)[1]}` : null);
  if (!title || !/^(Components|Patterns|Base|Foundations)\//.test(title)) continue;
  const component = meta.match(/component:\s*([A-Z]\w*)/)?.[1];
  const from = component && s.match(new RegExp(`import\\s*\\{[^}]*\\b${component}\\b[^}]*\\}\\s*from\\s*'(\\.[^']+)'`))?.[1];
  const srcFile = from && [`.tsx`, `/index.tsx`].map(ext => `src/${f.replace(/[^/]+$/, '')}${from}${ext}`)
    .map(p => p.replace(/\/\.\//g, '/')).find(p => existsSync(p));
  const what = srcFile ? purpose(readFileSync(srcFile, 'utf8'), component) : '';
  const stories = [...s.matchAll(/^export const ([A-Z]\w*)\s*:\s*Story\b/gm)].map(m => m[1].replace(/(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])/g, ' '));
  const parts = title.split('/');
  const group = parts.slice(0, -1).join(' / ');
  const base = parts[0] === 'Base';
  const tag = base ? (/'covered'/.test(meta) ? ' (primitive; hidden: a Component replaces it)' : ' (primitive)')
    : /not-in-figma/.test(s) ? ' (not in Figma)' : '';
  const line = `- **${parts.at(-1)}**${component ? ` \`${component}\`` : ''}${tag}${what ? `: ${what}` : ''}` +
    (stories.length ? ` Stories: ${stories.join(', ')}.` : '');
  if (tag && !base) notInFigma.push(parts.at(-1));
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push(line);
}

// In the sidebar's order: Foundations, Components, Patterns, then Base, groups A–Z; Base under the line that says
// what it is.
const BASE_NOTE = 'React Aria parts painted with the tokens. Primitives: don\'t use them directly in pages; prefer the ' +
  'Components entry; when a page truly needs one, import it from `govocal-ds/base`.';
const TIERS = ['Foundations', 'Components', 'Patterns', 'Base'];
const rank = g => TIERS.indexOf(g.split(' / ')[0]);
const ordered = [...groups].sort(([a], [b]) => rank(a) - rank(b) || a.localeCompare(b));
const body = [`# Components index`, ``,
  `Generated by \`npm run components:index\` from the stories; never edit by hand. One line per Storybook entry:`,
  `name, export, what it is for, its stories (each story is a configuration to copy). Search it before drawing UI;`,
  `then open that entry's stories file for the usage. Import paths and props: docs/API.md.`, ``,
  ...ordered.flatMap(([g, lines]) => [`## ${g}`, ...(g === 'Base' ? [BASE_NOTE, ``] : []), ...lines, ``]),
  `## Not in Figma yet`, `Tagged \`not-in-figma\` in their stories (${notInFigma.length}): ${notInFigma.join(', ')}.`, ``].join('\n');

if (process.argv.includes('--check')) {
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (now !== body) { console.error(`${OUT} is stale: run npm run components:index`); process.exit(1); }
} else {
  writeFileSync(OUT, body);
  console.log(`${OUT}: ${[...groups.values()].flat().length} entries, ~${Math.round(body.length / 4)} tokens`);
}
