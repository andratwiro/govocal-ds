const rgb = c => {
  const [r, g, b] = c.components.map(v => Math.round(v * 255));
  return c.alpha >= 1 ? c.hex : `rgb(${r} ${g} ${b} / ${c.alpha})`;
};
const ref = v => `var(--gv-${v.slice(1, -1).replaceAll('.', '-')})`;
const dim = d => `${d.value}${d.unit}`;

export function toCss(tokens) {
  const lines = [];
  for (const [family, steps] of Object.entries(tokens.color))
    for (const [step, t] of Object.entries(steps)) lines.push(`--gv-color-${family}-${step}: ${rgb(t.$value)};`);
  const families = new Set(Object.values(tokens.type).map(t => t.$value.fontFamily));
  if (families.size !== 1) throw new Error(`expected one font family, got ${[...families]}`);
  lines.push(`--gv-font-family: '${[...families][0]}', system-ui, sans-serif;`);
  for (const [group, roles] of Object.entries(tokens)) {
    if (['color', 'space', 'radius', 'type', 'shadow'].includes(group)) continue;
    for (const [role, t] of Object.entries(roles)) lines.push(`--gv-${group}-${role}: ${ref(t.$value)};`);
  }
  for (const [n, t] of Object.entries(tokens.space)) lines.push(`--gv-space-${n}: ${dim(t.$value)};`);
  for (const [n, t] of Object.entries(tokens.radius)) lines.push(`--gv-radius-${n}: ${dim(t.$value)};`);
  for (const [role, t] of Object.entries(tokens.type)) {
    const v = t.$value, line = Math.round(v.fontSize.value * v.lineHeight);
    lines.push(`--gv-type-${role}: ${v.fontWeight} ${dim(v.fontSize)}/${line}px var(--gv-font-family);`);
    lines.push(`--gv-type-${role}-tracking: ${dim(v.letterSpacing)};`);
  }
  for (const [name, t] of Object.entries(tokens.shadow))
    lines.push(`--gv-shadow-${name}: ${t.$value.map(s =>
      `${dim(s.offsetX)} ${dim(s.offsetY)} ${dim(s.blur)} ${dim(s.spread)} ${rgb(s.color)}`).join(', ')};`);
  return `/* Generated by scripts/build-tokens.mjs from tokens/foundations.tokens.json. Do not edit by hand. */\n` +
    `:root {\n${lines.map(l => `  ${l}`).join('\n')}\n}\n`;
}
