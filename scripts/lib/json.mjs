import {cssOf} from './names.mjs';

// public/tokens.json: the merged token set as one DTCG 2025.10 file, published beside Storybook (dist/tokens.json) as
// the closed set an agent picks from. The same tree tokens.css is built from: every token keeps its $type, its $value
// (references stay references: {color.slate.100}), its $description and its $extensions, and gains two: its CSS name
// and, when Figma has a variable for it, that variable's id (tokens/variable-ids.json; of the ids merged into one
// name, the one that was already called so).
const isToken = node => node !== null && typeof node === 'object' && '$value' in node;

export function toJson(tokens, variableIds = {}, renames = {renames: []}) {
  const merged = new Set(renames.renames.filter(r => r.merge && r.figmaId).map(r => r.figmaId));
  const idsOf = new Map();
  for (const [id, name] of Object.entries(variableIds)) if (name) idsOf.set(name, [...(idsOf.get(name) ?? []), id]);
  const idOf = name => { const ids = idsOf.get(name) ?? []; return ids.find(id => !merged.has(id)) ?? ids[0]; };
  const walk = (node, path) => Object.fromEntries(Object.entries(node).map(([key, child]) => {
    if (key.startsWith('$') || typeof child !== 'object' || child === null) return [key, child];
    if (!isToken(child)) return [key, walk(child, [...path, key])];
    const css = cssOf(...path, key), id = idOf(css);
    const {['com.figma.variableId']: own, ...rest} = child.$extensions ?? {};
    return [key, {...child, $extensions: {...rest, 'com.govocal.css': css, ...(id || own ? {'com.figma.variableId': id ?? own} : {})}}];
  }));
  return {
    $description: 'Go Vocal design tokens (DTCG 2025.10): every --gv-* custom property in src/tokens.css, with its value, ' +
      'what it is for and its Figma variable id. Generated by npm run tokens:build from tokens/; do not edit. Paint with ' +
      'the semantic groups (surface, text, icon, border), never with color.*; docs/NAMING.md "Token names" has the grammar.',
    ...walk(Object.fromEntries(Object.entries(tokens).filter(([k]) => !k.startsWith('$'))), [])
  };
}
